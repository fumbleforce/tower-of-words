#!/usr/bin/env python3
"""The layout rules for island/private/ (rules and reasons: island/PRIVATE.md, Layout).

  python3 tools/private_layout.py           check: exit 1 on a new top-level violation (legacy names pass)
  python3 tools/private_layout.py --report  list everything that does not conform, legacy included
  python3 tools/private_layout.py resolve <path>  the place an older name now has (the `moved` map), printed under island/private/

Never opens, lists or reads island/private/user/. Passes when island/private/ does not exist (a fresh checkout, CI).
Imported by .claude/hooks/private_layout.py for the Write/Edit guard.
"""
import json
import os
import re
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PRIVATE = os.path.join(ROOT, 'island', 'private')


def spec():
    with open(os.path.join(HERE, 'private-layout.json'), encoding='utf-8') as f:
        return json.load(f)


def rewards_entry_problem(name, s, is_file):
    """None if `name` may sit at the top of rewards/, else why not."""
    r = s['rewards']
    if name in r['legacy'] or name in r['flat_rounds_legacy']:
        return None
    if is_file:
        if name in r['fixed_files'] or re.match(r['doc_regex'], name):
            return None
        return 'a file here must be one of ' + ', '.join(r['fixed_files']) + ', or an UPPERCASE.md doc; other docs go in rewards/docs/, scene data is generated by rewards/tools/day1-scenes.src.mjs'
    if name in r['fixed_dirs'] or name in r['projects']:
        return None
    return ('a new round nests under a project: rewards/<project>/<topic>-<n>/ with project one of ' + ', '.join(r['projects'])
            + '. A new project is a layout change: edit tools/private-layout.json and island/PRIVATE.md with Jørgen\'s word')


def project_entry_problem(project, name, s, is_file):
    """None if `name` may sit directly inside rewards/<project>/."""
    if project == 'archive':
        return None
    if is_file:
        return None if name == 'index.html' else 'only index.html (the project summary) sits at the top of a project'
    if re.match(s['rewards']['round_regex'], name):
        return None
    pd = s['rewards'].get('project_dirs', {}).get(project)
    if pd and re.match(pd, name):
        return None  # the promoted pictures: d<N>/<scene id>/<n>.webp
    return f'a round inside {project}/ is named <topic>-<n> (for example aoi-2): lower-case, dashes, a number at the end'


def resolve(path, s=None):
    """The current place of `path` (under island/private/, with or without that prefix). Only a name in the `moved` map of
    rewards/ changes; a current file at the top of rewards/ (index.html, the redirect) never does. Text only: no file is read."""
    s = s or spec()
    rel = path.replace('\\', '/').strip('/')
    if rel.startswith('island/private/'):
        rel = rel[len('island/private/'):]
    if not rel.startswith('rewards/'):
        return rel
    r = s['rewards']
    parts = rel[len('rewards/'):].split('/')
    if len(parts) == 1 and parts[0] in r['fixed_files']:
        return rel
    for i in range(len(parts), 0, -1):
        key = '/'.join(parts[:i])
        if key in r['moved']:
            return '/'.join(['rewards', r['moved'][key]] + parts[i:])
    return rel


def path_problem(rel, s=None):
    """Why a write to island/private/<rel> breaks the layout, or None. rel uses / and has no leading /."""
    s = s or spec()
    parts = [p for p in rel.replace('\\', '/').split('/') if p]
    if not parts:
        return None
    top = parts[0]
    if top == s['user_only']:
        return 'island/private/user/ is Jørgen\'s alone: no agent reads, lists, writes or moves anything there'
    if top not in s['top']:
        return f'island/private/{top} is not a known top-level folder ({", ".join(s["top"])})'
    if top in s['dashboard_only']:
        return 'island/private/imagegen/ is written only by the dashboard (tools/imagegen); agents change presets only through its API'
    if top == 'plugins':
        if len(parts) != 2 or not parts[1].endswith('.js'):
            return 'plugins/ is flat: one <place>.js per place, plus kit.js, boot.js, viewer*.js'
        return None
    if top == 'game':
        g = s['game']
        if len(parts) == 1:
            return None
        if len(parts) == 2:
            return None if parts[1] in g['files'] or parts[1] in g['dirs'] else 'game/ holds ' + ', '.join(g['files'] + list(g['dirs'])) + ' and nothing else'
        if parts[1] not in g['dirs']:
            return 'game/ holds ' + ', '.join(g['files'] + list(g['dirs'])) + ' and nothing else'
        if parts[1] == 'encounters' and len(parts) != 3:
            return 'game/encounters/ is flat'
        return None
    if top == 'audio':
        if len(parts) != 2 or not (parts[1] == 'index.json' or parts[1].endswith('.mp3')):
            return 'audio/ is flat: <line id>.mp3 and index.json'
        return None
    if top == 'rewards' and len(parts) >= 2:
        why = rewards_entry_problem(parts[1], s, len(parts) == 2)
        if why or parts[1] not in s['rewards']['projects'] or len(parts) < 3:
            return why
        return project_entry_problem(parts[1], parts[2], s, len(parts) == 3)
    return None


def scan():
    """(errors, notes) for the real tree. Errors: new top-level violations. Notes: legacy and in-round hygiene."""
    s = spec()
    errors, notes = [], []
    if not os.path.isdir(PRIVATE):
        return errors, notes
    for name in sorted(os.listdir(PRIVATE)):
        if name == s['user_only']:
            continue  # never listed
        if name in s.get('legacy_top', {}):
            notes.append((f'island/private/{name}', 'legacy: ' + s['legacy_top'][name]))
        elif name not in s['top']:
            errors.append((f'island/private/{name}', 'not a known top-level folder'))
    game = os.path.join(PRIVATE, 'game')
    if os.path.isdir(game):
        for name in sorted(os.listdir(game)):
            why = path_problem('game/' + name, s)
            if why:
                errors.append((f'island/private/game/{name}', why))
    rew = os.path.join(PRIVATE, 'rewards')
    if not os.path.isdir(rew):
        return errors, notes
    r = s['rewards']
    for name in sorted(os.listdir(rew)):
        full = os.path.join(rew, name)
        is_file = os.path.isfile(full)
        if name in r['legacy']:
            notes.append((f'island/private/rewards/{name}', 'legacy: ' + r['legacy'][name]))
            continue
        if name in r['flat_rounds_legacy']:
            notes.append((f'island/private/rewards/{name}', 'flat round, to move to rewards/' + r.get('moved', {}).get(name, '<project>/<topic>-<n>')))
            continue
        if not is_file and name in r['projects']:
            for sub in sorted(os.listdir(full)):
                why = project_entry_problem(name, sub, s, os.path.isfile(os.path.join(full, sub)))
                if why:
                    errors.append((f'island/private/rewards/{name}/{sub}', why))
            continue
        why = rewards_entry_problem(name, s, is_file)
        if why:
            errors.append((f'island/private/rewards/{name}', why))
            continue
        if not is_file and re.match(r['round_regex'], name):
            files = os.listdir(full)
            if 'index.html' not in files and name not in ('encounters',):
                notes.append((f'island/private/rewards/{name}', 'round has no index.html'))
            pngs = [f for f in files if f.endswith('.png') and f[:-4] + '.webp' in files]
            if pngs:
                notes.append((f'island/private/rewards/{name}', f'{len(pngs)} PNG copies sit beside their .webp; raw PNGs go in raw/ or are deleted'))
    return errors, notes


def main():
    if sys.argv[1:2] == ['resolve'] and len(sys.argv) == 3:
        print('island/private/' + resolve(sys.argv[2]))
        return 0
    report = '--report' in sys.argv
    errors, notes = scan()
    for path, why in errors:
        print(f'FAIL {path}: {why}')
    if report:
        for path, why in notes:
            print(f'note {path}: {why}')
    if not errors:
        print('private layout: ok' + (f' ({len(notes)} notes)' if notes else ''))
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main())
